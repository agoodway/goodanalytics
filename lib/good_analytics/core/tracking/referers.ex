defmodule GoodAnalytics.Core.Tracking.Referers do
  @moduledoc """
  Referrer and source lookups backed by the vendored referrer database.

  `priv/referers/referers.yml` (generated by `mix good_analytics.referers.update`
  from the Snowplow referer-parser and Matomo lists plus a small hand-kept
  supplement) is compiled into module attributes, so lookups are map reads with
  no startup work, database query or cache.

  Mediums map from the list sections: `search` -> `:organic`, `social`,
  `email`, `paid`, `chatbot` -> `:ai`, `unknown` -> `:referral`,
  plus `:ignore` for hand-offs that are never an acquisition source.
  """

  alias GoodAnalytics.Core.Tracking.Referers.{Data, Key}

  @data_path Path.expand("../../../../priv/referers/referers.yml", __DIR__)
  @supplement_path Path.expand("../../../../priv/referers/good_analytics_referers.yml", __DIR__)
  @external_resource @data_path
  @external_resource @supplement_path

  # Generic words that must never resolve through the alias table. The table
  # ignores a trailing `.com`, so `Mail.com` or `Search.com` would otherwise
  # claim `utm_source=mail` or `search`. Their hosts still resolve.
  @alias_stoplist ~w(mail search you pi web app)

  # Alias keys shorter than this are kept only when the hand-kept supplement
  # lists them (`fb`, `ig`, `li`, `x`): two-letter keys are too easy to hit by
  # accident.
  @min_alias_length 3

  @medium_by_section Data.section_mediums()

  # Which medium a platform is reported as when only its name is known
  # (`utm_source=linkedin`), most specific first.
  @primary_medium_order [:ai, :social, :organic, :email, :paid, :referral]

  # A `google.{}` pattern may stand in for these final labels only: a single
  # label (`de`) or a country second-level plus ccTLD (`co.uk`, `com.hk`).
  @second_levels ~w(co com org net ac gov edu ne or go)

  @data Data.load_merged!(File.read!(@data_path))

  entries =
    for entry <- @data.entries do
      Map.put(entry, :platform_atom, String.to_atom(entry.platform))
    end

  @hosts for entry <- entries,
             domain <- entry.domains,
             not String.ends_with?(domain, ".{}"),
             into: %{},
             do: {domain, {entry.platform_atom, Map.fetch!(@medium_by_section, entry.medium)}}

  @wildcards for entry <- entries,
                 domain <- entry.domains,
                 String.ends_with?(domain, ".{}"),
                 into: %{},
                 do: {domain, {entry.platform_atom, Map.fetch!(@medium_by_section, entry.medium)}}

  # The first entry in file order names the platform. The file is ordered by
  # medium section first; source precedence (supplement, then Snowplow, then
  # Matomo) only applies within a section.
  @names Enum.reduce(entries, %{}, fn entry, acc ->
           Map.put_new(acc, entry.platform_atom, entry.name)
         end)

  @explicit_aliases @supplement_path
                    |> File.read!()
                    |> Data.load_merged!()
                    |> Map.fetch!(:aliases)
                    |> Map.keys()

  @aliases for {key, platform} <- @data.aliases,
               key not in @alias_stoplist,
               byte_size(key) >= @min_alias_length or key in @explicit_aliases,
               into: %{},
               do: {key, String.to_atom(platform)}

  @primary_media Enum.reduce(entries, %{}, fn entry, acc ->
                   medium = Map.fetch!(@medium_by_section, entry.medium)
                   Map.update(acc, entry.platform_atom, [medium], &[medium | &1])
                 end)
                 |> Map.new(fn {platform, media} ->
                   {platform, Enum.find(@primary_medium_order, :referral, &(&1 in media))}
                 end)

  @social_platforms entries
                    |> Enum.filter(&(&1.medium == "social"))
                    |> MapSet.new(& &1.platform_atom)

  @ai_platforms entries
                |> Enum.filter(&(&1.medium == "chatbot"))
                |> MapSet.new(& &1.platform_atom)

  # Every key a stored `source_platform` may take for a social network (or an AI
  # assistant): the platform slugs plus the alias keys (`meta`, `x`) that resolve
  # to them.
  platform_keys = fn platforms ->
    # A slug that is also an alias for another platform belongs to that platform
    # (the alias wins on lookup), so it is left out here.
    (for(
       platform <- platforms,
       slug = Atom.to_string(platform),
       Map.get(@aliases, slug, platform) == platform,
       do: slug
     ) ++
       for({key, platform} <- @aliases, platform in platforms, do: key))
    |> Enum.uniq()
    |> Enum.sort()
  end

  @social_platform_keys platform_keys.(@social_platforms)
  @ai_platform_keys platform_keys.(@ai_platforms)

  # Platform keys grouped by each platform's primary medium. A platform has one
  # primary medium, so the groups are disjoint by construction (aliases map to
  # one platform each).
  @primary_platform_keys (for medium <- [:ai, :social, :organic, :email, :paid], into: %{} do
                            platforms =
                              for {platform, ^medium} <- @primary_media, do: platform

                            {medium, platform_keys.(platforms)}
                          end)

  @type result :: %{platform: atom(), medium: atom(), name: String.t()}

  @doc """
  Looks up a host (or a URL, or an `android-app://<package>` referrer).

  Tries the exact host, then drops the leftmost label while at least two
  labels remain, so `mail3.spectrum.net` matches `spectrum.net` but a bare TLD
  or a foreign suffix (`brave.com.evil.net`) never matches. TLD wildcards such
  as `google.{}` match `google.de` and `google.co.uk`.

  Returns `%{platform: atom, medium: atom, name: String.t()}` or `nil`. A
  medium of `:ignore` marks a hand-off that is never an acquisition source.
  """
  @spec lookup(String.t() | nil) :: result() | nil
  def lookup(value) when is_binary(value) do
    case host(value) do
      nil -> nil
      host -> host |> candidates() |> Enum.find_value(&match_candidate/1) |> to_result()
    end
  end

  def lookup(_), do: nil

  @doc """
  Extracts the lowercase host from a URL, protocol-relative URL (`//host/x`),
  `android-app://` referrer or bare host.

  A bare value is accepted only when it looks like a hostname or Android
  package: dotted labels of letters, digits, `-` and `_`, no spaces. Anything
  else (`"garbage"`, free text) returns `nil`.
  """
  @spec host(String.t()) :: String.t() | nil
  def host(value) when is_binary(value), do: extract_host(String.trim(value), false)

  def host(_), do: nil

  @doc """
  Comparable host: `host/1` lowercased, with a leading `www.` and any port
  removed. Accepts a URL or a bare host (`"WWW.Example.com:8080"` ->
  `"example.com"`); returns `nil` for `nil` or anything that is not a host.

  A single-label host such as `localhost` is not a valid lookup host, so it
  returns `nil` unless `allow_single_label: true` (used to compare dev hosts).
  """
  @spec bare_host(String.t() | nil, keyword()) :: String.t() | nil
  def bare_host(value, opts \\ [])

  def bare_host(value, opts) when is_binary(value) do
    value
    |> String.trim()
    |> then(&Regex.replace(~r/\A([^\/?#:]+):\d+(?=[\/?#]|\z)/, &1, "\\1"))
    |> extract_host(Keyword.get(opts, :allow_single_label, false))
    |> case do
      nil -> nil
      host -> String.replace_prefix(host, "www.", "")
    end
  end

  def bare_host(_, _opts), do: nil

  @doc """
  The hosts tried for a lookup: the host itself, then each parent while at
  least two labels remain (never a bare TLD).
  """
  @spec candidates(String.t()) :: [String.t()]
  def candidates(host) when is_binary(host) do
    labels = String.split(host, ".", trim: true)
    count = length(labels)

    if count < 2 do
      []
    else
      for drop <- 0..(count - 2), do: labels |> Enum.drop(drop) |> Enum.join(".")
    end
  end

  @doc """
  Resolves a free-form source name such as a `utm_source` value.

  Matches it as a host first (`copilot.com`), then through the alias index
  (`perplexity`, `meta`). The medium is the platform's primary medium.
  Returns `nil` when unknown, and for ignored hand-offs.
  """
  @spec resolve(String.t() | nil) :: result() | nil
  def resolve(value) when is_binary(value) do
    case lookup(value) do
      %{medium: :ignore} -> nil
      %{} = found -> found
      nil -> resolve_alias(value)
    end
  end

  def resolve(_), do: nil

  @doc """
  Canonical platform key for a platform name or atom, applying the aliases
  (`meta` and `facebook` -> `:facebook`, `x` and `twitter` -> `:twitter`).
  Case, a leading `www.`, `.com` and punctuation are ignored. Returns `nil`
  when the value matches no known platform.
  """
  @spec canonical_platform(String.t() | atom() | nil) :: atom() | nil
  def canonical_platform(nil), do: nil

  def canonical_platform(value) when is_atom(value),
    do: value |> Atom.to_string() |> canonical_platform()

  def canonical_platform(value) when is_binary(value) do
    case Key.normalize(value) do
      nil -> nil
      key -> Map.get(@aliases, key)
    end
  end

  @doc """
  Display name for a platform (`:gmail` -> `"Gmail"`), or `nil` when unknown.
  Aliases are applied first, so `:meta` is `"Facebook"`.
  """
  @spec name(atom() | String.t() | nil) :: String.t() | nil
  def name(platform) do
    case canonical_platform(platform) do
      nil -> nil
      canonical -> Map.get(@names, canonical)
    end
  end

  @doc """
  Lowercase platform keys of every social network in the vendored data
  (slugs and aliases such as `"meta"`), sorted. Used to tell paid social from
  paid search.
  """
  @spec social_platform_keys() :: [String.t()]
  def social_platform_keys, do: @social_platform_keys

  @doc """
  Lowercase platform keys (slugs and aliases) whose platform's primary medium is
  `medium` (`:ai`, `:social`, `:organic`, `:email` or `:paid`). The lists are
  disjoint. Raises `KeyError` for any other medium.
  """
  @spec primary_platform_keys(:ai | :social | :organic | :email | :paid) :: [String.t()]
  def primary_platform_keys(medium), do: Map.fetch!(@primary_platform_keys, medium)

  @doc """
  Lowercase platform keys of every AI assistant in the vendored data (slugs and
  aliases such as `"perplexity_ai"`), sorted.
  """
  @spec ai_platform_keys() :: [String.t()]
  def ai_platform_keys, do: @ai_platform_keys

  # -- Private --

  defp resolve_alias(value) do
    with platform when not is_nil(platform) <- canonical_platform(value),
         medium when not is_nil(medium) <- Map.get(@primary_media, platform) do
      %{platform: platform, medium: medium, name: Map.get(@names, platform)}
    end
  end

  defp extract_host(value, allow_single_label?) do
    candidate =
      if String.contains?(value, "://") or String.starts_with?(value, "//") do
        URI.parse(value).host
      else
        value |> String.split(["/", "?", "#"], parts: 2) |> hd()
      end

    candidate
    |> to_string()
    |> String.downcase()
    |> String.trim_trailing(".")
    |> valid_host(allow_single_label?)
  end

  defp valid_host(host, allow_single_label?) do
    cond do
      host =~ ~r/\A[a-z0-9_]([a-z0-9_\-]*[a-z0-9_])?(\.[a-z0-9_]([a-z0-9_\-]*[a-z0-9_])?)+\z/ ->
        host

      allow_single_label? and host =~ ~r/\A[a-z0-9_]([a-z0-9_\-]*[a-z0-9_])?\z/ ->
        host

      true ->
        nil
    end
  end

  defp match_candidate(candidate) do
    case Map.fetch(@hosts, candidate) do
      {:ok, found} -> found
      :error -> match_wildcard(candidate)
    end
  end

  defp match_wildcard(candidate) do
    labels = String.split(candidate, ".")
    count = length(labels)

    Enum.find_value(1..2, fn tail_size ->
      {prefix, tail} = Enum.split(labels, count - tail_size)

      if prefix != [] and tld_like?(tail) do
        Map.get(@wildcards, Enum.join(prefix, ".") <> ".{}")
      end
    end)
  end

  defp tld_like?([tld]), do: alpha?(tld, 2..24)
  defp tld_like?([second, cc]), do: second in @second_levels and alpha?(cc, 2..2)
  defp tld_like?(_), do: false

  defp alpha?(label, size_range),
    do: String.length(label) in size_range and label =~ ~r/\A[a-z]+\z/

  defp to_result(nil), do: nil

  defp to_result({platform, medium}),
    do: %{platform: platform, medium: medium, name: Map.get(@names, platform)}
end
