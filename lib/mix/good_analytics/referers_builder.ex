defmodule Mix.GoodAnalytics.Referers.Builder do
  @moduledoc """
  Builds the vendored referrer database (`priv/referers/referers.yml`).

  **Build-time only.** Used by `mix good_analytics.referers.update` to merge the
  hand-kept supplement, the Snowplow referer-parser database and the Matomo
  searchengine-and-social-list into one Snowplow-format file. The runtime
  library only reads that file, through
  `GoodAnalytics.Core.Tracking.Referers.Data`.

  Precedence on a host conflict is supplement, then Snowplow, then Matomo.

  YAML syntax errors in the (vendored, trusted) input raise from `yamerl`
  rather than returning a tuple; the update task simply fails on bad upstream
  data.
  """

  alias GoodAnalytics.Core.Tracking.Referers.{Data, Key}

  @mediums Data.sections()
  @matomo_sections [
    {"SearchEngines.yml", "search"},
    {"Socials.yml", "social"},
    {"AIAssistants.yml", "chatbot"}
  ]

  @type entry :: Data.entry()

  @doc "Matomo files fetched by the update task, with the section each maps to."
  @spec matomo_sections() :: [{String.t(), String.t()}]
  def matomo_sections, do: @matomo_sections

  @doc "Parses a YAML binary into a map (`%{}` for an empty document)."
  @spec parse!(binary()) :: map()
  def parse!(yaml) when is_binary(yaml) do
    case :yamerl_constr.string(yaml, [:str_node_as_binary, {:map_node_format, :map}]) do
      [doc | _] when is_map(doc) -> doc
      _ -> %{}
    end
  end

  @doc """
  Merges the three parsed sources (`matomo` is a list of `{section, doc}`)
  into `%{aliases: map, entries: [entry]}`.
  """
  @spec build(map(), map(), [{String.t(), map()}]) :: %{aliases: map(), entries: [entry()]}
  def build(supplement, snowplow, matomo) do
    hand_aliases = hand_aliases(supplement)

    # Each source is name-sorted for a deterministic file; sources stay in
    # precedence order and the medium sort below is stable.
    raw =
      Enum.flat_map(
        [
          sectioned_entries(supplement, true),
          sectioned_entries(snowplow, false),
          Enum.flat_map(matomo, fn {section, doc} -> matomo_entries(section, doc) end)
        ],
        &Enum.sort_by(&1, fn e -> e.name end)
      )

    entries =
      raw
      |> Enum.map(&assign_platform(&1, hand_aliases))
      |> Enum.reject(&is_nil/1)
      |> dedupe_hosts()
      |> merge_same_name()
      |> Enum.sort_by(fn e -> Enum.find_index(@mediums, &(&1 == e.medium)) end)

    %{aliases: alias_index(entries, hand_aliases), entries: entries}
  end

  @doc "Renders a built database as YAML, with the provenance header line."
  @spec render(%{aliases: map(), entries: [entry()]}, String.t(), String.t(), Date.t()) ::
          String.t()
  def render(%{aliases: aliases, entries: entries}, snowplow_sha, matomo_sha, date) do
    header = [
      "# snowplow: #{snowplow_sha}, matomo: #{matomo_sha}, generated: #{Date.to_iso8601(date)}\n",
      "#\n",
      "# Generated by `mix good_analytics.referers.update`. Do not edit by hand;\n",
      "# edit good_analytics_referers.yml and re-run the task instead.\n",
      "# Precedence: supplement > Snowplow referer-parser > Matomo.\n\n"
    ]

    alias_lines =
      ["aliases:\n"] ++
        for {k, v} <- Enum.sort(aliases), do: "  #{quote_str(k)}: #{quote_str(v)}\n"

    sections =
      for medium <- @mediums, group = Enum.filter(entries, &(&1.medium == medium)), group != [] do
        ["\n#{medium}:\n" | Enum.map(group, &render_entry/1)]
      end

    IO.iodata_to_binary([header, alias_lines, sections])
  end

  @doc "Summarises a rebuilt database against the previous merged document."
  @spec diff_summary(map() | nil, %{entries: [entry()]}) :: map()
  def diff_summary(old_doc, %{entries: entries}) do
    new_hosts = entries |> Enum.flat_map(& &1.domains) |> MapSet.new()
    old_hosts = old_doc |> doc_hosts() |> MapSet.new()

    %{
      entries: length(entries),
      hosts: MapSet.size(new_hosts),
      added: new_hosts |> MapSet.difference(old_hosts) |> MapSet.size(),
      removed: old_hosts |> MapSet.difference(new_hosts) |> MapSet.size()
    }
  end

  # -- Source parsing --

  defp hand_aliases(supplement) do
    for {k, v} <- Map.get(supplement, "aliases", %{}),
        key = Key.normalize(k),
        target = Key.slug(v),
        into: %{},
        do: {key, target}
  end

  defp sectioned_entries(doc, supplement?) do
    for medium <- @mediums,
        {name, body} <- Map.get(doc, medium, %{}),
        body = body || %{} do
      %{
        medium: medium,
        name: to_string(name),
        platform_hint: if(supplement?, do: body["platform"]),
        domains: body |> Map.get("domains") |> clean_domains(),
        utm_sources: body |> Map.get("utm_sources") |> List.wrap(),
        supplement?: supplement?
      }
    end
  end

  defp matomo_entries("search", doc) do
    for {name, variants} <- doc, is_list(variants) do
      urls = for variant <- variants, is_map(variant), url <- List.wrap(variant["urls"]), do: url
      matomo_entry("search", name, urls)
    end
  end

  defp matomo_entries(section, doc) do
    for {name, domains} <- doc, is_list(domains), do: matomo_entry(section, name, domains)
  end

  defp matomo_entry(section, name, urls) do
    %{
      medium: section,
      name: to_string(name),
      platform_hint: nil,
      domains: clean_domains(urls),
      utm_sources: [],
      supplement?: false
    }
  end

  # Normalises list hosts: lowercases, drops `www.` and a leading `{}.`
  # (any-subdomain), keeps a trailing `.{}` (any TLD), skips path-qualified
  # entries, and reduces Matomo `android-app//<package>/...` to the package.
  defp clean_domains(list) do
    list |> List.wrap() |> Enum.map(&clean_domain/1) |> Enum.reject(&is_nil/1) |> Enum.uniq()
  end

  defp clean_domain(raw) do
    raw |> to_string() |> String.trim() |> String.downcase() |> clean_host()
  end

  defp clean_host("android-app//" <> rest), do: rest |> String.split("/") |> hd() |> clean_host()
  defp clean_host("{}." <> rest), do: clean_host(rest)
  defp clean_host("www." <> rest), do: clean_host(rest)
  defp clean_host(""), do: nil

  defp clean_host(host) do
    cond do
      String.contains?(host, "/") -> nil
      String.contains?(String.replace_suffix(host, ".{}", ""), "{}") -> nil
      true -> host
    end
  end

  # -- Merging --

  defp assign_platform(entry, hand_aliases) do
    platform =
      case entry.platform_hint do
        hint when is_binary(hint) -> Key.slug(hint)
        _ -> hand_alias_platform(entry.name, hand_aliases) || Key.slug(entry.name)
      end

    if platform, do: entry |> Map.put(:platform, platform) |> Map.delete(:platform_hint)
  end

  # A hand alias may be keyed by how the list spells the name (`Outlook.com`
  # normalises to `outlook`) or by its slug (`outlook_com`).
  defp hand_alias_platform(name, hand_aliases) do
    Map.get(hand_aliases, Key.normalize(name)) ||
      Map.get(hand_aliases, Key.normalize(Key.slug(name)))
  end

  # Entries arrive in precedence order, so the first claim on a host wins.
  # Matomo/Snowplow entries left with no hosts are dropped; supplement entries
  # are kept because they may exist only to name a platform or add aliases.
  defp dedupe_hosts(entries) do
    {kept, _seen} =
      Enum.reduce(entries, {[], MapSet.new()}, fn entry, {acc, seen} ->
        domains = Enum.reject(entry.domains, &MapSet.member?(seen, &1))
        seen = Enum.reduce(domains, seen, &MapSet.put(&2, &1))

        if domains == [] and not entry.supplement? do
          {acc, seen}
        else
          {[%{entry | domains: domains} | acc], seen}
        end
      end)

    Enum.reverse(kept)
  end

  defp merge_same_name(entries) do
    entries
    |> Enum.reduce({[], %{}}, fn entry, {order, by_key} ->
      key = {entry.medium, entry.name}

      case by_key do
        %{^key => existing} ->
          merged = %{existing | domains: existing.domains ++ entry.domains}
          {order, Map.put(by_key, key, merged)}

        _ ->
          {[key | order], Map.put(by_key, key, entry)}
      end
    end)
    |> then(fn {order, by_key} ->
      order |> Enum.reverse() |> Enum.map(&Map.fetch!(by_key, &1))
    end)
    |> Enum.map(&Map.put(&1, :domains, Enum.sort(&1.domains)))
  end

  defp alias_index(entries, hand_aliases) do
    Enum.reduce(entries, hand_aliases, fn entry, acc ->
      [entry.name, entry.platform | entry.utm_sources]
      |> Enum.map(&Key.normalize/1)
      |> Enum.reject(&is_nil/1)
      |> Enum.reduce(acc, &Map.put_new(&2, &1, entry.platform))
    end)
  end

  # -- Rendering --

  defp render_entry(entry) do
    domains =
      case entry.domains do
        [] -> ["    domains: []\n"]
        list -> ["    domains:\n" | Enum.map(list, &"      - #{quote_str(&1)}\n")]
      end

    ["  #{quote_str(entry.name)}:\n", "    platform: #{quote_str(entry.platform)}\n" | domains]
  end

  defp quote_str(value), do: Jason.encode!(to_string(value))

  defp doc_hosts(nil), do: []

  defp doc_hosts(doc) do
    for medium <- @mediums,
        {_name, body} <- Map.get(doc, medium, %{}),
        host <- body["domains"] || [],
        do: host
  end
end
